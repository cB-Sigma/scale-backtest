// Registry resolves metric names.
type Registry struct {
	names map[string]Ref
}

// NewRegistry returns a registry with the built-in names.
func NewRegistry() *Registry {
	r := &Registry{names: make(map[string]Ref, len(builtin))}
	for _, a := range builtin {
		r.names[a.Name] = a.Ref
	}
	return r
}

// Builtin returns the built-in name table, for documentation.
func Builtin() []Alias { return append([]Alias(nil), builtin...) }

// Alias makes name refer to whatever the existing name target refers to.
func (r *Registry) Alias(name, target string) error {
	ref, ok := r.names[target]
	if !ok {
		return fmt.Errorf("metric alias %q: unknown target %q", name, target)
	}
	if name == "" {
		return fmt.Errorf("metric alias: empty name")
	}
	r.names[name] = ref
	return nil
}

// Resolve looks a name up.
func (r *Registry) Resolve(name string) (Ref, bool) {
	ref, ok := r.names[name]
	return ref, ok
}

// UnknownError builds the error for a name that is not mapped.
func UnknownError(name string) error {
	return fmt.Errorf("metric %q is not mapped to a simulated metric; see docs/algorithms.md#metric-names or add --metric-alias %s=<known name>", name, name)
}

// Values is one scrape of every series of one target.
type Values [NumSeries]float64

type sample struct {
	t float64
	v Values
}

type history struct {
	samples []sample
}

func (h *history) add(t float64, v Values, retention float64) {
	h.samples = append(h.samples, sample{t, v})
	// Drop samples older than the retention, keeping the slice compact.
	cut := 0
	for cut < len(h.samples)-1 && h.samples[cut].t < t-retention {
		cut++
	}
	if cut > 0 && cut >= len(h.samples)/2 {
		n := copy(h.samples, h.samples[cut:])
		h.samples = h.samples[:n]
	}
}

func (h *history) latest(now, staleness float64) (sample, bool) {
	if h == nil || len(h.samples) == 0 {
		return sample{}, false
	}
	s := h.samples[len(h.samples)-1]
	if now-s.t > staleness {
		return sample{}, false
	}
	return s, true
}

// rate returns (last-first)/(tLast-tFirst) over the samples inside the
// window. Unlike Prometheus it does not extrapolate to the window edges.
func (h *history) rate(now, window float64, s Series) (float64, bool) {
	if h == nil {
		return 0, false
	}
	lo := now - window
	first := -1
	for i := len(h.samples) - 1; i >= 0; i-- {
		if h.samples[i].t < lo {
			break
		}
		first = i
	}
	last := len(h.samples) - 1
	if first < 0 || first == last {
		return 0, false
	}
	dt := h.samples[last].t - h.samples[first].t
	if dt <= 0 {
		return 0, false
	}
	return (h.samples[last].v[s] - h.samples[first].v[s]) / dt, true
}

// Store keeps scraped samples per replica and for the gateway.
type Store struct {
	pods      map[int]*history
	gateway   history
	retention float64
	// Staleness is how old the latest sample of a series may be before the
	// series is treated as absent (Prometheus' lookback is 5 minutes).
	Staleness float64
	// DefaultRateWindow is the window used for *_per_second names.
	DefaultRateWindow float64
}

// NewStore returns an empty store that keeps retention seconds of samples.
func NewStore(retention float64) *Store {
	return &Store{pods: map[int]*history{}, retention: retention, Staleness: 300, DefaultRateWindow: 60}
}

// Scrape records one scrape of a replica.
func (s *Store) Scrape(t float64, pod int, v Values) {
	h := s.pods[pod]
	if h == nil {
		h = &history{}
		s.pods[pod] = h
	}
	h.add(t, v, s.retention)
}

// ScrapeGateway records one scrape of the gateway.
func (s *Store) ScrapeGateway(t float64, v Values) { s.gateway.add(t, v, s.retention) }

// Forget drops a replica's series (the pod is gone).
func (s *Store) Forget(pod int) { delete(s.pods, pod) }

// PodValue returns the value a custom-metrics adapter would report for one
// replica: the latest scraped gauge, or the rate of a counter over the
// default window.
func (s *Store) PodValue(now float64, pod int, ref Ref) (float64, bool) {
	return s.value(now, s.pods[pod], ref, s.DefaultRateWindow)
}

func (s *Store) value(now float64, h *history, ref Ref, window float64) (float64, bool) {
	if ref.Rate {
		if _, ok := h.latest(now, s.Staleness); !ok {
			return 0, false
		}
		return h.rate(now, window, ref.Series)
	}
	smp, ok := h.latest(now, s.Staleness)
	if !ok {
		return 0, false
	}
	return smp.v[ref.Series], true
}

func (s *Store) podIDs() []int {
	ids := make([]int, 0, len(s.pods))
	for id := range s.pods {
		ids = append(ids, id)
	}
	sort.Ints(ids)
	return ids
}

// Total returns the sum of a metric over all replicas (or the gateway value),
// the way the external metrics API sums matching series. empty is true when
// no series had a value.
func (s *Store) Total(now float64, ref Ref) (total float64, empty bool) {
	if infos[ref.Series].Gateway {
		v, ok := s.value(now, &s.gateway, ref, s.DefaultRateWindow)
		return v, !ok
	}
	empty = true
	for _, id := range s.podIDs() {
		if v, ok := s.value(now, s.pods[id], ref, s.DefaultRateWindow); ok {
			total += v
			empty = false
		}
	}
	return total, empty
}

// Query evaluates a parsed PromQL query whose selector resolved to ref.
// empty is true when the query selects no series; the value is then 0, which
// is what KEDA's prometheus scaler reports with its default
// ignoreNullValues=true.
func (s *Store) Query(now float64, q *promql.Query, ref Ref) (value float64, empty bool, err error) {
	info := infos[ref.Series]
	if q.Rate && !info.Counter {
		return 0, false, fmt.Errorf("rate() over %s, which is a gauge", q.Metric)
	}
	if !q.Rate && info.Counter && !ref.Rate {
		return 0, false, fmt.Errorf("%s is a counter; wrap it in rate(...[window])", q.Metric)
	}
	if q.Rate && ref.Rate {
		return 0, false, fmt.Errorf("%s is already a per-second rate", q.Metric)
	}
	eff := ref
	window := s.DefaultRateWindow
	if q.Rate {
		eff.Rate = true
		window = q.WindowSeconds
	}

	var vals []float64
	if info.Gateway {
		if v, ok := s.value(now, &s.gateway, eff, window); ok {
			vals = append(vals, v)
		}
	} else {
		for _, id := range s.podIDs() {
			if v, ok := s.value(now, s.pods[id], eff, window); ok {
				vals = append(vals, v)
			}
		}
	}
	if len(vals) == 0 {
		return 0, true, nil
	}
	switch q.Agg {
	case "":
		if len(vals) > 1 {
			return 0, false, fmt.Errorf("query %q returns %d series; it must return a single value (aggregate it with sum() or avg())", q.Raw, len(vals))
		}
		value = vals[0]
	case "sum":
		for _, v := range vals {
			value += v
		}
	case "avg":
		for _, v := range vals {
			value += v
		}
		value /= float64(len(vals))
	case "max":
		value = math.Inf(-1)
		for _, v := range vals {
			value = math.Max(value, v)
		}
	case "min":
		value = math.Inf(1)
		for _, v := range vals {
			value = math.Min(value, v)
		}
	default:
		return 0, false, fmt.Errorf("unsupported aggregation %q", q.Agg)
	}
	return value * q.Scale, false, nil
}

// CheckQuery validates at load time that a query can be evaluated.
func (r *Registry) CheckQuery(q *promql.Query) (Ref, error) {
	ref, ok := r.Resolve(q.Metric)
	if !ok {
		return Ref{}, UnknownError(q.Metric)
	}
	info := infos[ref.Series]
	switch {
	case q.Rate && ref.Rate:
		return Ref{}, fmt.Errorf("query %q: %s is already a per-second rate", q.Raw, q.Metric)
	case q.Rate && !info.Counter:
		return Ref{}, fmt.Errorf("query %q: rate() over %s, which is a gauge", q.Raw, q.Metric)
	case !q.Rate && info.Counter && !ref.Rate:
		return Ref{}, fmt.Errorf("query %q: %s is a counter; wrap it in rate(...[window])", q.Raw, q.Metric)
	case q.Agg == "" && !info.Gateway:
		return Ref{}, fmt.Errorf("query %q selects one series per replica; aggregate it with sum() or avg() so it returns a single value", q.Raw)
	}
	return ref, nil
}
