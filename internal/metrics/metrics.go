// Series identifies one simulated time series (per replica, or one for the
// gateway).
type Series int

// The simulated series.
const (
	RequestsRunning   Series = iota // gauge, per replica
	RequestsWaiting                 // gauge, per replica
	KVCacheUsage                    // gauge 0..1, per replica (proxy)
	GPUUtilization                  // gauge 0..100, per replica (proxy)
	GenerationTokens                // counter, per replica
	PromptTokens                    // counter, per replica
	RequestsCompleted               // counter, per replica
	GatewayPending                  // gauge, gateway
	GatewayInFlight                 // gauge, gateway
	GatewayRequests                 // counter, gateway
	NumSeries
)

// Info describes a series.
type Info struct {
	Canonical   string
	Counter     bool
	Gateway     bool
	Description string
}

