// Describe returns the description of a series.
func (s Series) Describe() Info { return infos[s] }

func (s Series) String() string { return infos[s].Canonical }

// Ref is a resolved metric name: a series, or the per-second rate of a
// counter series.
type Ref struct {
	Series Series
	// Rate is true when the name denotes the per-second rate of a counter
	// (the way a custom metrics adapter usually exposes counters).
	Rate bool
}

// Alias documents one accepted metric name.
type Alias struct {
	Name string
	Ref  Ref
	Note string
}

